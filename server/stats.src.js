function bars(rows, label, max) {
  if (!rows.length) return '<p class="none">まだありません</p>';
  const top = max || Math.max(...rows.map(r => r.n));
  return '<ol class="bars">' + rows.map(r => '<li><span class="bl" title="' + esc(r.title || label(r)) + '">' + esc(label(r)) + '</span><span class="bt"><i style="width:' + (r.n / top * 100).toFixed(1) + '%"></i></span><b>' + r.n + '</b></li>').join('') + '</ol>';
}
function daily(rows, days) {
  const by = Object.fromEntries(rows.map(r => [r.day, r])), list = [];
  for (let i = days - 1; i >= 0; i--) { const d = jstDay(Date.now() - i * 86400e3); list.push({ d, n: by[d] ? by[d].n : 0, done: by[d] ? by[d].done || 0 : 0 }); }
  const max = Math.max(1, ...list.map(x => x.n)), md = d => Number(d.slice(5, 7)) + '/' + Number(d.slice(8));
  return '<div class="daily' + (days > 30 ? ' dense' : '') + '" role="img" aria-label="日ごとのゲーム数（最大 ' + max + '）"><div class="dcols">' +
    list.map(x => '<span class="dc" title="' + md(x.d) + '：' + x.n + 'ゲーム（最後まで ' + x.done + '）"><i style="height:' + (x.n ? Math.max(2, x.n / max * 100) : 0).toFixed(1) + '%"></i></span>').join('') +
    '</div><div class="daxis"><span>' + md(list[0].d) + '</span><span>いちばん多い日 ' + max + '</span><span>' + md(list[list.length - 1].d) + '</span></div></div>';
}
/* mini games played from cards: how often each was played, out of how often its card came up */
function played(rows, offered) {
  const by = {};
  offered.forEach(r => { by[r.k] = { k: r.k, n: 0, seen: r.n }; });
  rows.forEach(r => { (by[r.k] = by[r.k] || { k: r.k, n: 0, seen: 0 }).n = r.n; });
  const list = Object.values(by).sort((a, b) => b.n - a.n || b.seen - a.seen);
  if (!list.length) return '<p class="none">まだありません</p>';
  const top = Math.max(1, ...list.map(r => r.n));
  return '<ol class="bars">' + list.map(r => '<li><span class="bl">' + esc(NAMES[r.k] || r.k) + '</span><span class="bt"><i style="width:' + (r.n / top * 100).toFixed(1) + '%"></i></span><b>' + r.n +
    (r.seen ? '<small>出た' + r.seen + '回中 ' + Math.min(100, Math.round(r.n * 100 / r.seen)) + '%</small>' : '') + '</b></li>').join('') + '</ol>';
}

