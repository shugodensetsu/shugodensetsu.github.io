const fails = new Map();   // sender -> [minute, wrong passwords], memory only
const sha = async t => new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(t)));
async function samePass(given, want) {   // compares hashes in full, so the time taken says nothing about the password
  const [a, b] = await Promise.all([sha(given), sha(want)]);
  let d = 0;
  for (let i = 0; i < a.length; i++) d |= a[i] ^ b[i];
  return d === 0;
}
async function gate(request, env, ctx) {
  if (ctx && ctx.access) {
    const who = await ctx.access.getIdentity().catch(() => null);
    return { ok: true, who: (who && who.email) || '' };
  }
  const want = typeof env.STATS_PASSWORD === 'string' ? env.STATS_PASSWORD : '';
  if (want.length < 16) return { status: 403 };
  const ip = request.headers.get('cf-connecting-ip') || '?', m = Math.floor(Date.now() / 60000), f = fails.get(ip);
  if (f && f[0] === m && f[1] >= 10) return { status: 429 };
  const h = request.headers.get('authorization') || '';
  if (/^Basic /i.test(h)) {
    let given = '';
    try { given = new TextDecoder().decode(Uint8Array.from(atob(h.slice(6).trim()), c => c.charCodeAt(0))); } catch (_) { given = ''; }
    if (given && await samePass(given.slice(given.indexOf(':') + 1), want)) return { ok: true, who: '' };
    if (!f || f[0] !== m) fails.set(ip, [m, 1]); else f[1]++;
    if (fails.size > 5000) fails.clear();
  }
  return { status: 401 };
}
