const enc = t => new TextEncoder().encode(t);
const sha = async t => new Uint8Array(await crypto.subtle.digest('SHA-256', enc(t)));
async function same(given, want) {   // compares hashes in full, so the time taken says nothing about either value
  const [a, b] = await Promise.all([sha(given), sha(want)]);
  let d = 0;
  for (let i = 0; i < a.length; i++) d |= a[i] ^ b[i];
  return d === 0;
}
const b64url = u8 => btoa(String.fromCharCode(...u8)).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
async function sign(text, pass) {
  const key = await crypto.subtle.importKey('raw', enc('sakego-session:' + pass), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return b64url(new Uint8Array(await crypto.subtle.sign('HMAC', key, enc(text))));
}
const passOf = env => (typeof env.STATS_PASSWORD === 'string' ? env.STATS_PASSWORD : '');
const senderOf = request => request.headers.get('cf-connecting-ip') || '?';
function slowed(request) {
  const m = Math.floor(Date.now() / 60000), f = fails.get(senderOf(request));
  return !!(f && f[0] === m && f[1] >= 10);
}
function missed(request) {
  const ip = senderOf(request), m = Math.floor(Date.now() / 60000), f = fails.get(ip);
  if (!f || f[0] !== m) fails.set(ip, [m, 1]); else f[1]++;
  if (fails.size > 5000) fails.clear();
}
function cookieOf(request) {
  const m = (request.headers.get('cookie') || '').match(new RegExp('(?:^|;\\s*)' + COOKIE + '=([^;]+)'));
  return m ? m[1] : '';
}
async function gate(request, env, ctx) {
  if (ctx && ctx.access) {
    const who = await ctx.access.getIdentity().catch(() => null);
    return { ok: true, who: (who && who.email) || '' };
  }
  const want = passOf(env);
  if (want.length < 16) return { status: 403 };
  const c = cookieOf(request), dot = c.indexOf('.');
  if (dot > 0) {
    const exp = Number(c.slice(0, dot));
    if (exp > Date.now() && await same(c.slice(dot + 1), await sign(String(exp), want))) return { ok: true, who: '', cookie: true };
  }
  if (slowed(request)) return { status: 429 };
  const h = request.headers.get('authorization') || '';
  if (/^Basic /i.test(h)) {
    let given = '';
    try { given = new TextDecoder().decode(Uint8Array.from(atob(h.slice(6).trim()), ch => ch.charCodeAt(0))); } catch (_) { given = ''; }
    if (given && await same(given.slice(given.indexOf(':') + 1), want)) return { ok: true, who: '' };
    missed(request);
  }
  return { status: 401 };
}
