/* builds server/src/stats.js (the dashboard) from tools/stats.src.js, with the built-in card texts and game names filled in.
   node server/tools/build-stats.js   (run it again when cards or game names change, then commit) */
const fs = require('fs'), path = require('path');
const dir = __dirname, src = path.join(dir, '..', '..', 'src');
const deck = JSON.parse(fs.readFileSync(path.join(src, 'deck.json'), 'utf8'));
const game = fs.readFileSync(path.join(src, 'part-game.js'), 'utf8');
const pick = re => { const m = re.exec(game); if (!m) throw new Error('not found: ' + re); return Function('return ' + m[1])(); };
const MINI = pick(/const MINI_NAMES = (\{[\s\S]*?\});/), SPECIAL = pick(/const SPECIAL_NAMES = (\[[\s\S]*?\]);/);
const names = Object.assign({}, MINI, Object.fromEntries(SPECIAL), { timer: '10秒ストップ・タイマー', tap: '早押し' });
const plain = t => t.replace(/\{([^}]+)\}/g, '$1').replace(/\s+/g, ' ').trim();
const cards = Object.fromEntries(deck.cards.map(c => [c.id, plain(c.text).slice(0, 48)]));
const out = fs.readFileSync(path.join(dir, 'stats.src.js'), 'utf8')
  .replace('__CARDS__', () => JSON.stringify(cards))
  .replace('__NAMES__', () => JSON.stringify(names))
  .replace('Generated by server/tools/build-stats.js from tools/stats.src.js — edit that file.', 'Generated by server/tools/build-stats.js from tools/stats.src.js — do not edit by hand.');
fs.writeFileSync(path.join(dir, '..', 'src', 'stats.js'), out);
console.log('stats.js', Buffer.byteLength(out), 'bytes,', Object.keys(cards).length, 'cards');
